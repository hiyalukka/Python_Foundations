#Create a dict where keys are student names and values are lists of marks (3 subjects each). Calculate and print each student's average. Print the name of the top scoring student.

students = {
    "Aman": [80, 85, 90],
    "Riya": [95, 88, 92],
    "Karan": [70, 75, 72]
}

top_student = ""
highest_avg = 0

for name, marks in students.items():
    avg = sum(marks) / len(marks)
    print(name, "Average =", avg)

    if avg > highest_avg:
        highest_avg = avg
        top_student = name

print("Top Student:", top_student)

