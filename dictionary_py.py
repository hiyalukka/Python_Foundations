#Problem 03
#Word frequency counter
#Take a sentence as a string. Count how many times each word appears. Store the result in a dictionary and print it sorted by frequency (most common first).

sentence = "python is easy and python is powerful"

words = sentence.split()
freq = {}

for word in words:
    freq[word] = freq.get(word, 0) + 1

sorted_freq = sorted(freq.items(), key=lambda x: x[1], reverse=True)

print(sorted_freq)

