#Problem 09
#Frequency analyser
#Take a paragraph as input. Count character frequency (letters only, case-insensitive). Print the top 5 most common characters. Then count word frequency and print the top 3 most common words.
#hardShow hint

paragraph = input("Enter paragraph: ").lower()

char_freq = {}
word_freq = {}

for ch in paragraph:
    if ch.isalpha():
        char_freq[ch] = char_freq.get(ch, 0) + 1

words = paragraph.split()

for word in words:
    word_freq[word] = word_freq.get(word, 0) + 1

top_chars = sorted(char_freq.items(), key=lambda x: x[1], reverse=True)

print("Top 5 Characters:")
print(top_chars[:5])

top_words = sorted(word_freq.items(), key=lambda x: x[1], reverse=True)

print("Top 3 Words:")
print(top_words[:3])

#Problem 10
#Mini contacts app
#Build a complete contacts manager using a dict. Features: add contact (name, phone, email), view all contacts, search by name, update a contact's details, delete a contact. Use a while loop menu to keep it running until the user exits.

contacts = {}

while True:

    print("\n1.Add")
    print("2.View")
    print("3.Search")
    print("4.Update")
    print("5.Delete")
    print("6.Exit")

    choice = input("Enter choice: ")

    if choice == "1":
        name = input("Name: ")

        contacts[name] = {
            "phone": input("Phone: "),
            "email": input("Email: ")
        }

    elif choice == "2":
        for name, info in contacts.items():
            print(name, info)

    elif choice == "3":
        name = input("Enter name: ")

        if name in contacts:
            print(contacts[name])
        else:
            print("Not found")

    elif choice == "4":
        name = input("Enter name: ")

        if name in contacts:
            contacts[name]["phone"] = input("New phone: ")
            contacts[name]["email"] = input("New email: ")

    elif choice == "5":
        name = input("Enter name: ")

        if name in contacts:
            del contacts[name]

    elif choice == "6":
        break

    else:
        print("Invalid choice")