def add_expense(expenses, item, amount):
    expenses[item] = amount

def get_total(expenses):
    return sum(expenses.values())

def get_average(expenses):
    return sum(expenses.values()) / len(expenses)

def get_highest(expenses):
    return max(expenses, key=expenses.get)

expenses = {}

add_expense(expenses, "Food", 500)
add_expense(expenses, "Travel", 1000)
add_expense(expenses, "Books", 700)

print(expenses)
print("Total:", get_total(expenses))
print("Average:", get_average(expenses))
print("Highest:", get_highest(expenses))

