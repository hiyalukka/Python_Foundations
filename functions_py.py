#Build a calculator where each operation (add, subtract, multiply, divide, power, modulo) is a separate function. Write a main() function that takes two numbers and an operator as input and calls the right function. Handle division by zero.

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):

    if b == 0:
        return "Cannot divide by zero"

    return a / b

def power(a, b):
    return a ** b

def modulo(a, b):
    return a % b


def main():

    a = float(input("Enter first number: "))
    b = float(input("Enter second number: "))

    op = input("Enter operator (+,-,*,/,**,%) : ")

    if op == "+":
        print(add(a, b))

    elif op == "-":
        print(subtract(a, b))

    elif op == "*":
        print(multiply(a, b))

    elif op == "/":
        print(divide(a, b))

    elif op == "**":
        print(power(a, b))

    elif op == "%":
        print(modulo(a, b))

    else:
        print("Invalid operator")

main()